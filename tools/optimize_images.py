"""Build web-sized copies of every image the site uses.

Run from the repository root:  python3 tools/optimize_images.py
- Reads image paths referenced in _posts, _data and the about pages.
- Writes img/web/800/... and img/web/1600/... as progressive JPEG (originals untouched).
- Writes _data/images.yml: original path -> small/large web paths + size, used by the templates.
- Rewrites image links inside _posts to the 1600 px version.
Re-run it after adding new works; already-built files are skipped.
"""
import glob, io, os, re
from PIL import Image, ImageOps

SIZES = {"s": 800, "l": 1600}
QUALITY = 82
ROOT = os.getcwd()

def referenced():
    refs = set()
    files = glob.glob("_posts/**/*.markdown", recursive=True) + glob.glob("_data/*.yml") + ["about.html", "fr/about.html", "biography.html", "fr/biography.html"]
    for f in files:
        if os.path.exists(f):
            refs.update(re.findall(r"(/img/(?!web/)[^)\s\"']+\.(?:jpe?g|png))", io.open(f, encoding="utf-8").read(), re.I))
    return sorted(r for r in refs if os.path.exists(r[1:]))

def web_path(src, width):
    rel = os.path.splitext(src[len("/img/"):])[0] + ".jpg"
    return f"/img/web/{width}/{rel}"

def build(src):
    im = Image.open(src[1:])
    im = ImageOps.exif_transpose(im)
    if im.mode in ("RGBA", "LA", "P"):
        im = im.convert("RGBA")
        bg = Image.new("RGB", im.size, (255, 255, 255))
        bg.paste(im, mask=im.split()[-1])
        im = bg
    else:
        im = im.convert("RGB")
    out = {"w": im.width, "h": im.height}
    for key, width in SIZES.items():
        dest = web_path(src, width)
        if not os.path.exists(dest[1:]):
            os.makedirs(os.path.dirname(dest[1:]), exist_ok=True)
            copy = im.copy()
            if copy.width > width:
                copy = copy.resize((width, round(copy.height * width / copy.width)), Image.LANCZOS)
            copy.save(dest[1:], "JPEG", quality=QUALITY, optimize=True, progressive=True)
        out[key] = dest
    return out

def main():
    refs = referenced()
    lines = ["# Generated by tools/optimize_images.py, do not edit by hand.\n"]
    for src in refs:
        d = build(src)
        lines.append(f'"{src}": {{ s: "{d["s"]}", l: "{d["l"]}", w: {d["w"]}, h: {d["h"]} }}\n')
    io.open("_data/images.yml", "w", encoding="utf-8").writelines(lines)
    # point work pages' images at the 1600 px copies
    for f in glob.glob("_posts/**/*.markdown", recursive=True):
        s = io.open(f, encoding="utf-8").read()
        head, sep, body = s.partition("\n---\n")
        body2 = re.sub(r"\]\((/img/(?!web/)[^)\s]+\.(?:jpe?g|png))\)",
                       lambda m: f"]({web_path(m.group(1), SIZES['l'])})" if os.path.exists(m.group(1)[1:]) else m.group(0), body, flags=re.I)
        if body2 != body:
            io.open(f, "w", encoding="utf-8").write(head + sep + body2)
    print(f"{len(refs)} images processed")

if __name__ == "__main__":
    main()
